def test_a_letterhead_crop_grows_over_adjoining_vector_artwork():
    """Content drawn as vector paths is invisible to both text extraction
    and page.images. A real package put the engineering firm's name, address
    and telephone number beside its logo as outlined shapes: cropping the
    logo bitmap alone cut the contact details off the right-hand edge.
    """
    from unittest import mock

    page = mock.Mock()
    page.bbox = (0.0, 0.0, 1224.0, 792.0)
    logo = {"x0": 778.0, "top": 31.0, "x1": 966.0, "bottom": 73.0}
    page.images = [logo]
    # The address block: vector artwork on the logo's rows, further right.
    page.rects = [{"x0": 980.0, "top": 33.0, "x1": 1150.0, "bottom": 70.0}]
    page.curves = []
    page.extract_words.return_value = [
        {"x0": 70.0, "top": 300.0, "x1": 300.0, "bottom": 315.0, "text": "body"}
    ]

    boxes, _ = ex._embedded_page_images(page)
    assert len(boxes) == 1
    x0, top, x1, bottom = boxes[0]
    assert x0 == 778.0 and x1 == 1150.0, "crop must reach the address block"
    # Rows grow to the artwork's own extent: vector lettering overshoots the
    # bitmap, and clipping it slices the first and last lines in half.
    assert top == 31.0 and bottom == 73.0


def test_the_crop_stops_rather_than_swallow_extracted_text():
    """Body text is already in the corpus; re-reading it as a picture would
    duplicate it. A word inside the widened band cancels the widening."""
    from unittest import mock

    page = mock.Mock()
    page.bbox = (0.0, 0.0, 1224.0, 792.0)
    logo = {"x0": 778.0, "top": 31.0, "x1": 966.0, "bottom": 73.0}
    page.images = [logo]
    page.rects = [{"x0": 980.0, "top": 33.0, "x1": 1150.0, "bottom": 70.0}]
    page.curves = []
    page.extract_words.return_value = [
        {"x0": 1000.0, "top": 40.0, "x1": 1100.0, "bottom": 55.0,
         "text": "ASCE"}
    ]

    boxes, _ = ex._embedded_page_images(page)
    assert boxes == [(778.0, 31.0, 966.0, 73.0)], \
        "a real word in the band must collapse the crop back to the figure"


