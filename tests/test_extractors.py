def test_docx_merged_cell_is_not_repeated_across_the_span(tmp_path):
    """A merged header must not widen the table with phantom copies of
    itself - the ownership matrix depends on column identity."""
    import docx
    d = docx.Document()
    t = d.add_table(rows=2, cols=3)
    t.cell(0, 0).merge(t.cell(0, 1))
    t.cell(0, 0).text = "Responsibility"
    t.cell(0, 2).text = "Owner"
    t.cell(1, 0).text = "Calibration"
    t.cell(1, 1).text = "System"
    t.cell(1, 2).text = "AVL"
    path = str(tmp_path / "RASIC.docx")
    d.save(path)

    got = ex.extract_docx(path)
    header = got.text.splitlines()[0]
    assert header.count("Responsibility") == 1
    assert "| Responsibility |  | Owner |" == header


