def test_rows_to_markdown_builds_a_header_and_separator():
    md = ex.rows_to_markdown([["Task", "Owner"], ["Calibration", "AVL"]])
    assert md.splitlines()[0] == "| Task | Owner |"
    assert md.splitlines()[1] == "| --- | --- |"
    assert md.splitlines()[2] == "| Calibration | AVL |"


def test_rows_to_markdown_pads_ragged_rows_and_drops_empty_ones():
    md = ex.rows_to_markdown([["A", "B", "C"], ["", "", ""], ["x"]])
    lines = md.splitlines()
    assert lines[0] == "| A | B | C |"
    assert lines[-1] == "| x |  |  |"
    assert len(lines) == 3          # header, separator, one body row


def test_rows_to_markdown_escapes_pipes_and_collapses_newlines():
    md = ex.rows_to_markdown([["H"], ["a|b"], ["two\nlines"]])
    assert r"a\|b" in md
    assert "| two lines |" in md


