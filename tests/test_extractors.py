def test_docx_paragraphs_and_tables(tmp_path):
    import docx
    d = docx.Document()
    d.add_paragraph("The system shall deliver 450 Nm.")
    t = d.add_table(rows=2, cols=2)
    t.cell(0, 0).text = "Task"
    t.cell(0, 1).text = "Owner"
    t.cell(1, 0).text = "Calibration"
    t.cell(1, 1).text = "AVL"
    path = str(tmp_path / "SOR.docx")
    d.save(path)

    got = ex.extract_docx(path)
    assert "The system shall deliver 450 Nm." in got.text
    assert "| Task | Owner |" in got.text
    assert "| Calibration | AVL |" in got.text
    assert got.images == []


def test_docx_embedded_image_becomes_a_marker_in_place(tmp_path):
    import docx
    from docx.shared import Inches
    png = tmp_path / "chart.png"
    png.write_bytes(_png_bytes())

    d = docx.Document()
    d.add_paragraph("Before the chart.")
    d.add_picture(str(png), width=Inches(2))
    d.add_paragraph("After the chart.")
    path = str(tmp_path / "SOR.docx")
    d.save(path)

    got = ex.extract_docx(path)
    assert len(got.images) == 1
    img = got.images[0]
    assert img.image_id == "SOR.docx__img01"
    assert img.data == _png_bytes()
    marker = ex.marker_for("SOR.docx__img01")
    assert marker in got.text
    # position preserved: the marker sits between the two paragraphs
    assert got.text.index("Before the chart.") < got.text.index(marker)
    assert got.text.index(marker) < got.text.index("After the chart.")


