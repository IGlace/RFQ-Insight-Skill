def test_a_figure_on_a_text_bearing_pdf_page_is_flagged_for_reading():
    """A page with a text layer can still hide content in its figures — a
    letterhead carrying a company name and phone, a chart, a scanned table.
    Native text extraction cannot see any of it, while the OCR-the-whole-page
    approach this skill replaced always could.

    Found by comparing a real run against the system being replaced: the old
    output carried "Affiliated Engineers, Inc." and a telephone number read
    out of a letterhead image; the new one reported no phone at all.
    """
    import pdfplumber
    from unittest import mock

    big = {"x0": 40.0, "top": 40.0, "x1": 340.0, "bottom": 190.0}   # 45,000 pt²
    small = {"x0": 10.0, "top": 10.0, "x1": 30.0, "bottom": 30.0}   # 400 pt²

    page = mock.Mock()
    page.images = [small, big]
    page.bbox = (0.0, 0.0, 612.0, 792.0)
    page.rects = []
    page.curves = []
    page.extract_words.return_value = []
    boxes, skipped = ex._embedded_page_images(page)

    assert boxes == [(40.0, 40.0, 340.0, 190.0)], \
        "only the figure above the size floor should be flagged"
    assert skipped == 1, "the sub-floor figure must be counted, not forgotten"


