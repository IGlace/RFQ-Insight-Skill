# Characters NFKD does not decompose to ASCII.
_TRANSLIT = str.maketrans({"ß": "ss", "đ": "d", "Đ": "d", "ø": "o",
                           "Ø": "o", "æ": "ae", "Æ": "ae", "ł": "l",
                           "Ł": "l", "œ": "oe", "Œ": "oe", "ı": "i"})

# Legal-form words carry no identity: the RFQ's "VINFAST Trading and
# Production JSC" is Salesforce's "VinFast Trading and Production".
# fold() reads "&" as "and", so "AG & Co. KG" arrives as "ag and co kg".
# Dotted forms join up (_join_initials): "A/S", "s.r.o.", "K.K." and
# "d.o.o." are "as", "sro", "kk" and "doo". "Tbk" is not one of them: TBK is
# a company in the list.
_LEGAL_PHRASES = ("joint stock company", "public limited company",
                  "limited liability company", "and company", "and co",
                  "s a de c v", "sa de cv", "sp z o o", "ges m b h",
                  "sdn bhd")
_LEGAL_WORDS = frozenset({
    "jsc", "gmbh", "mbh", "ltd", "limited", "co", "inc", "incorporated",
    "ag", "sa", "se", "kg", "kgaa", "ohg", "llc", "plc", "corp",
    "corporation", "company", "spa", "srl", "sarl", "sas", "bv", "nv", "pte",
    "pvt", "private", "oy", "oyj", "ab", "asa", "the", "as", "ltda", "sro",
    "kk", "pty", "llp", "doo", "kft", "aktiengesellschaft", "gesmbh"})

# The "contained" tier lists an account whose name words all appear in the
# customer's name only if that name is at least two words, or one word of
# this many letters: "Aurobay" in "Aurobay Sweden AB", but no short word
# such as "ISP" or "GM" on its own.
_MIN_CONTAINED_LETTERS = 5


def fold(text) -> str:
    """Lower-case ASCII, accents removed, '&' read as 'and', and every run
    of other characters turned into one space."""
    text = str(text or "").translate(_TRANSLIT)
    text = unicodedata.normalize("NFKD", text)
    text = "".join(c for c in text if not unicodedata.combining(c)).lower()
    text = text.replace("&", " and ")
    return re.sub(r"[^a-z0-9]+", " ", text).strip()


def _join_initials(tokens) -> list:
    """'s a s' -> 'sas': dotted abbreviations ("S.A.S.", "A.G.") fold to
    single letters; joined back they match the legal-form list."""
    out, run = [], ""
    for token in tokens:
        if len(token) == 1 and token.isalpha():
            run += token
            continue
        if run:
            out.append(run)
            run = ""
        out.append(token)
    if run:
        out.append(run)
    return out


def normalize_name(text) -> str:
    """The identity key of a company name."""
    folded = f" {fold(text)} "
    for phrase in _LEGAL_PHRASES:
        folded = folded.replace(f" {phrase} ", " ")
    return " ".join(t for t in _join_initials(folded.split())
                    if t not in _LEGAL_WORDS)


@functools.lru_cache(maxsize=None)
def load_guidance(path=None) -> dict:
    """accounts.csv + vocabularies.json as one dict; `path` is the folder."""
    folder = Path(path or GUIDANCE_DIR)
    data = json.loads((folder / "vocabularies.json").read_text(encoding="utf-8"))
    with open(folder / "accounts.csv", encoding="utf-8-sig", newline="") as fh:
        data["accounts"] = list(csv.DictReader(fh))
    for index, account in enumerate(data["accounts"]):
        account["index"] = index
        account["key"] = normalize_name(account["base"])
        account["display_name"] = re.sub(r"\s+", " ", account["name"]).strip()
    return data


@functools.lru_cache(maxsize=None)
def _index(path=None):
    data = load_guidance(path)
    by_key, by_token = {}, {}
    for account in data["accounts"]:
        by_key.setdefault(account["key"], []).append(account)
        for token in set(account["key"].split()):
            by_token.setdefault(token, set()).add(account["index"])
    return by_key, by_token


def vocabulary(kind: str, path=None) -> list:
    """The official names of one vocabulary, in workbook order."""
    if kind not in VOCABULARIES:
        raise ValueError(f"Unknown vocabulary: {kind!r}")
    return [item["name"] for item in load_guidance(path)[kind]]


def _candidates(name, path=None):
    """(tier, accounts) for the best tier that matches at all:
    exact key > every name word present > fuzzy (>= FUZZY_CUTOFF) >
    contained (every word of the account's name is in the customer's name:
    "Aurobay" for "Aurobay Sweden AB", see _MIN_CONTAINED_LETTERS)."""
    key = normalize_name(name)
    if not key:
        return "none", []
    data = load_guidance(path)
    by_key, by_token = _index(path)
    if key in by_key:
        return "exact", list(by_key[key])
    words = key.split()
    sets = [by_token.get(token, set()) for token in words]
    hits = set.intersection(*sets) if sets and all(sets) else set()
    if hits:
        return "tokens", [data["accounts"][i] for i in sorted(hits)]
    close = difflib.get_close_matches(key, list(by_key), n=5,
                                      cutoff=FUZZY_CUTOFF)
    if close:
        return "fuzzy", [a for k in close for a in by_key[k]]
    contained = []
    for index in sorted(set().union(*sets)):
        account = data["accounts"][index]
        own = account["key"].split()
        if set(own) <= set(words) and (
                len(own) > 1 or len(own[0]) >= _MIN_CONTAINED_LETTERS):
            contained.append(account)
    if contained:
        return "contained", contained
    return "none", []


def _public(account, match, score=1.0) -> dict:
    return {"account_name": account["display_name"],
            "site": account["site"], "country": account["country"],
            "kam_pte": account["kam_pte"],
            "kam_company": account["kam_company"],
            "match": match, "score": round(score, 3)}


def search_accounts(name, country=None, site=None, limit=10,
                    path=None) -> list:
    """Candidate accounts for a customer name, best first. `country` keeps
    exact-country rows only; `site` keeps rows whose site contains it."""
    tier, accounts = _candidates(name, path)
    if country:
        wanted = fold(country)
        accounts = [a for a in accounts if fold(a["country"]) == wanted]
    if site:
        wanted = fold(site)
        accounts = [a for a in accounts if wanted and wanted in fold(a["site"])]
    key = normalize_name(name)
    scored = sorted(
        ((difflib.SequenceMatcher(None, key, a["key"]).ratio(), a)
         for a in accounts),
        key=lambda pair: (-pair[0], pair[1]["index"]))
    return [_public(a, tier, score) for score, a in scored[:limit]]


