"""The AVL Guidance Document as the skill ships it: references/data/
accounts.csv + vocabularies.json (generated by Backlog/tests/tools/build_guidance.py).

Two jobs:
  * the official Opportunity Info vocabularies (project types, technologies,
    industries, products, skills) that rfq/validation.py checks the analysis
    against;
  * the Salesforce account list (26 784 rows), searched here so that no
    model and no coordinator ever has to load it.

Accuracy beats coverage: an account is only returned when its name is
the customer's name (legal forms aside); a partly matching, similar or
contained name is listed, never chosen, and AVL itself is never the
customer. When several accounts share the name, resolve_account() picks
one only by the customer's own address, and never between sites the
address cannot tell apart (a more detailed site, the same place spelled
two ways). Without an address the rest of the RFQ text can only confirm
the only account with the name by naming its country. A wrong account is
worse than "Info not available".
"""

