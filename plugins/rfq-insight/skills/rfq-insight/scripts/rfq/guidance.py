class _Address(NamedTuple):
    """The customer's own address, read for matching (_read_address)."""
    text: str               # as given, quoted in the reasons
    places: frozenset       # its place parts
    countries: tuple        # the countries it names, sorted
    words: frozenset        # every word of it, street parts included


def _mentions(text: str, phrase: str) -> bool:
    """`phrase` appears in the folded text as whole words."""
    return bool(phrase) and f" {phrase} " in text


def _match_form(text) -> str:
    """fold() with apostrophes joined first: "Xi'an" is "xian", never the
    two words "xi an"."""
    return fold(_APOSTROPHES.sub("", str(text or "")))


def _no_digits(text) -> str:
    """`text` without the words holding a digit (postcodes, house
    numbers)."""
    return " ".join(t for t in str(text or "").split()
                    if not any(c.isdigit() for c in t))


def _words(part) -> str:
    """An address or site part in match form, without the words holding a
    digit (postcodes, house numbers). They go whole before folding, so a
    prefixed postcode leaves nothing behind: "D-70372 Stuttgart" is
    "stuttgart", not "d stuttgart"."""
    return _no_digits(_match_form(_no_digits(part)))


def _place(words: str) -> str:
    """`words` without trailing administrative suffixes, never down to
    nothing: "changwon si" -> "changwon", "gyeonggi do" -> "gyeonggi",
    "si" stays "si"."""
    tokens = words.split()
    while len(tokens) > 1 and tokens[-1] in _PLACE_SUFFIXES:
        tokens.pop()
    return " ".join(tokens)


@functools.lru_cache(maxsize=None)
def _country_phrases(path=None) -> dict:
    """Folded phrase -> country, for every country of the account list
    (folded and in match form: "cote d ivoire", "cote divoire") and its
    aliases."""
    phrases = {}
    for account in load_guidance(path)["accounts"]:
        if fold(account["country"]):
            phrases[fold(account["country"])] = account["country"]
            phrases[_match_form(account["country"])] = account["country"]
    for alias, name in _COUNTRY_ALIASES.items():
        if fold(name) in phrases:
            phrases[alias] = phrases[fold(name)]
    return phrases


def _countries_in(text: str, path=None) -> list:
    """The countries a folded, padded text names, sorted."""
    return sorted({country
                   for phrase, country in _country_phrases(path).items()
                   if _mentions(text, phrase)})


def _country_named(account, countries) -> bool:
    return fold(account["country"]) in {fold(c) for c in countries}


@functools.lru_cache(maxsize=None)
def _place_countries(path=None) -> dict:
    """Place key (_place_keys) -> the countries of every account whose site
    has that place as a whole part (_site_parts), built once per account
    list: "ningbo" -> {"China"}, "london" -> {"Canada", "Netherlands",
    "United Kingdom"}. Parts that name no specific place (a country, a
    region or label, fewer than three letters) are left out."""
    phrases = _country_phrases(path)
    index = {}
    for account in load_guidance(path)["accounts"]:
        if not fold(account["country"]):
            continue
        for part in _site_parts(account):
            if (sum(c.isalpha() for c in part) >= _MIN_PLACE_LETTERS
                    and part not in _NOT_A_PLACE and part not in phrases):
                for key in _place_keys([part]):
                    index.setdefault(key, set()).add(account["country"])
    return index


def _implied_country(address, path=None) -> tuple:
    """(country, its places) when the address names no country but its
    place parts imply one: every place part the account list has as a site
    part (_place_countries) appears there under the same one country -
    "Ningbo, Zhejiang" lies in China. ("", ()) when the address names a
    country, no part is found, a part appears under several countries
    ("London") or the parts disagree ("Ningbo, Graz")."""
    if address.countries:
        return "", ()
    index = _place_countries(path)
    found = {}
    for place in address.places:
        (key,) = _place_keys([place])
        if key in index:
            found[place] = index[key]
    countries = set().union(*found.values())
    if len(countries) != 1:
        return "", ()
    return countries.pop(), tuple(sorted(found))


def _is_place(account, path=None) -> bool:
    """The account's site names a specific place, judged on the whole site:
    not a country ("Opel (Germany)"), region or label, and at least three
    letters ("Nabtesco (HQ)" names none)."""
    phrase = _match_form(account["site"])
    return (sum(c.isalpha() for c in phrase) >= _MIN_PLACE_LETTERS
            and phrase not in _NOT_A_PLACE
            and phrase not in _country_phrases(path))


def _is_street(words: str) -> bool:
    """The address part is a street, a lot or a P.O. box ("derby road")."""
    return (bool(set(words.split()) & _STREET_WORDS)
            or any(_mentions(f" {words} ", p) for p in _STREET_PHRASES))


def _site_parts(account) -> list:
    """The account's site part by part, none left out: "Kassel - Baunatal"
    is "kassel" and "baunatal", "Kansas City, MO" "kansas city" and "mo"."""
    return [_place(_words(part))
            for part in _PART_SPLIT.split(account["site"])]


def _word_set(words: str) -> set:
    """The words of a match-form text, "...strasse" written "...str" as in
    "Stuttgart-Haldenstr.", one spelling per place (_SPELLINGS)."""
    return {_SPELLINGS.get(w, re.sub(r"strasse$", "str", w))
            for w in words.split()}


def _place_keys(parts) -> set:
    """Place parts compared without their spaces and with one spelling per
    place (_SPELLINGS): "Chon Buri" is "Chonburi", "Göteborg" is
    "Gothenburg", "Miyako-gun" and "Miyakogun" are "Miyako"."""
    keys = {part.replace(" ", "") for part in parts}
    return {_SPELLINGS.get(key, key) for key in keys}


def _site_words(account) -> set:
    """Every word of the account's site, its hyphens splitting words:
    "Seosan-Jigok" is "seosan" and "jigok"."""
    return set().union(*(_word_set(part) for part in _site_parts(account)))


def _read_address(own_site: str, path=None) -> _Address:
    """The customer's own address split into parts (on , ; / newlines and
    " - "). A part that is a country or an alias ("Republic of Korea", "US",
    "Allemagne") only names that country; street parts ("Hauptstrasse 5",
    "PO Box 31") and parts left empty are ignored; every other part is a
    place. All its words, street parts included, are kept as well
    (_fits_words)."""
    phrases = {**_country_phrases(path), **_COUNTRY_PARTS}
    places, countries, words_seen = set(), set(), set()
    for part in _PART_SPLIT.split(own_site):
        words = _words(part)
        words_seen |= _word_set(words)
        if words in phrases:
            countries.add(phrases[words])
        elif words and not _is_street(words):
            places.add(_place(words))
    return _Address(own_site, frozenset(places), tuple(sorted(countries)),
                    frozenset(words_seen))


def _names_site(account, address, path=None) -> bool:
    """Every part of the account's site (a real place) IS a place part of
    the address - equal, not inside one: "Neu-Ulm" is no Ulm, and "Kansas
    City, MO" needs both "Kansas City" and "MO". Spaces and the spellings
    of _SPELLINGS do not count (_place_keys)."""
    return (_is_place(account, path)
            and _place_keys(_site_parts(account))
            <= _place_keys(address.places))


def _fits_words(account, address) -> bool:
    """Every word of the account's site is a word of the address, street
    parts included: "Daegu-Dalseong" fits "Dalseong-gun, Daegu, Korea",
    "Stuttgart-Haldenstr." fits "Haldenstrasse 1, 70376 Stuttgart"."""
    return all(_word_set(part) <= address.words
               for part in _site_parts(account))


def _inside_address(account, address) -> bool:
    """Every part of the account's site lies inside a longer place part of
    the address, as whole words ("neckarsulm" in "werk neckarsulm")."""
    return all(any(_mentions(f" {place} ", part) for place in address.places)
               for part in _site_parts(account))


def _wider(account, other) -> bool:
    """The account's site has every part of the other's site and more:
    "Viggen Way, Coventry" next to "Coventry"."""
    return _place_keys(_site_parts(other)) < _place_keys(_site_parts(account))


def _more_detailed(account, other) -> bool:
    """The account's site has every word of the other's site and more:
    "Seosan-Jigok" next to "Seosan", "Sakai Takumi" next to "Sakai",
    "Viggen Way, Coventry" next to "Coventry"."""
    return _site_words(other) < _site_words(account)


def _could_be(account, address, path=None) -> bool:
    """The account's site is a real place, in a country the address names
    if it names any."""
    return (_is_place(account, path)
            and (not address.countries
                 or _country_named(account, address.countries)))


def _not_ruled_out(named, distinct, address, path=None) -> list:
    """The other accounts (_could_be) that the address does not name but
    cannot rule out either, so a named account is not chosen alone:
      * a more detailed site: every word of a named account's site and more
        (_more_detailed), whether or not the address has the extra words -
        "Seosan-Jigok" next to "Seosan", "Viggen Way, Coventry" next to
        "Coventry";
      * a site inside a longer address part ("Neckarsulm" in "Werk
        Neckarsulm", "Seoul" in "HQ: Seoul");
      * a site whose words all appear in the address, street parts included
        (_fits_words): "Daegu-Dalseong" for "Dalseong-gun, Daegu".
    These only ever stop a choice; they never make one."""
    if not named:
        return []
    return [a for a in distinct
            if a not in named and _could_be(a, address, path)
            and (_inside_address(a, address) or _fits_words(a, address)
                 or any(_more_detailed(a, n) for n in named))]


def _fold_cased(text) -> str:
    """fold() without the lower-casing: accents removed, capitals kept."""
    text = str(text or "").translate(_TRANSLIT_CASED)
    text = unicodedata.normalize("NFKD", text)
    text = "".join(c for c in text if not unicodedata.combining(c))
    text = text.replace("&", " and ")
    return re.sub(r"[^A-Za-z0-9]+", " ", text).strip()


def _cut_names(words, names) -> list:
    """`words` with every whole-word occurrence of a name replaced by "|"
    (longest name first, case ignored)."""
    phrases = sorted({tuple(fold(n).split()) for n in names} - {()},
                     key=len, reverse=True)
    lowered = [w.lower() for w in words]
    out, i = [], 0
    while i < len(words):
        for phrase in phrases:
            if tuple(lowered[i:i + len(phrase)]) == phrase:
                out.append("|")
                i += len(phrase)
                break
        else:
            out.append(words[i])
            i += 1
    return out


def _drop_avl_country(unit) -> str:
    """One sentence or line (a regex match) without "Austria" ("Österreich")
    if it names AVL, else unchanged."""
    text = unit.group()
    return _AVL_COUNTRY.sub(" ", text) if _AVL.search(text) else text


def _without_avl_country(corpus_text) -> str:
    """The RFQ text without AVL's own country: "Austria" ("Österreich") is
    removed from every sentence and every line naming AVL ("To: AVL List
    GmbH ... 8020 Graz, Austria"). Every other word still counts: "BMW
    Group, Munich, Germany, requests AVL to quote" names Germany."""
    text = _SENTENCE.sub(_drop_avl_country, str(corpus_text or ""))
    return _LINE.sub(_drop_avl_country, text)


def _rfq_countries(corpus_text, names, path=None) -> list:
    """The countries the RFQ text names, for the country check only:
      * AVL's own country is removed (_without_avl_country);
      * the customer's and the candidates' names are cut out ("Schaeffler
        India" names no country);
      * only words starting with a capital count ("china" is tableware).
    A line break or a cut leaves "|", so no name is matched across it."""
    words = []
    for line in _without_avl_country(corpus_text).splitlines():
        words += _fold_cased(line).split() + ["|"]
    kept = [w.lower() if (not w[0].isalpha() or w[0].isupper()
                          or w.lower() in _COUNTRY_CONNECTORS) else "|"
            for w in _cut_names(words, names)]
    return _countries_in(f" {' '.join(kept)} ", path)


def _key(account):
    return (account["display_name"].lower(), account["kam_pte"])


def _distinct(accounts) -> list:
    """Identical rows (same name, same KAM) count once; rows that differ in
    their KAM stay separate, so they can never be merged silently."""
    seen, out = set(), []
    for account in accounts:
        if _key(account) not in seen:
            seen.add(_key(account))
            out.append(account)
    return out


def _by_own_site(accounts, distinct, single, address, path=None):
    """(chosen account or None, accounts tied for it, rule) from the
    customer's own address - the only evidence that chooses:
      * "own_site": the accounts whose site the address names
        (_names_site), less those in a country the address does not name,
        plus the accounts it cannot rule out (_not_ruled_out: a more
        detailed site, a site inside a longer address part, a site whose
        words all appear in the address); one is the answer, several stay
        tied - a city row and its province row, "Seosan" and
        "Seosan-Jigok", "Gurgaon" and "Gurugram" are never told apart by
        guessing;
      * "more_places": that one answer is not chosen, because the address
        names no country and has place parts its site does not account
        for ("London, ON" for a London account);
      * "no_country": the address names no country, and the accounts with
        this name are not all in one country - nothing is chosen;
      * "own_country": no site is named, and the only exact-name account
        has no specific place but the address names its country;
      * "implied_country": the same, but the address names no country and
        its places imply the account's (_implied_country) - used nowhere
        else;
      * "other_implied_country": its places imply another country;
      * "not_own_country": that account's country is not in the address;
      * otherwise "own_site" with nothing chosen."""
    named = [a for a in distinct if _names_site(a, address, path)]
    if not address.countries and named and len(
            {fold(a["country"]) for a in accounts}) > 1:
        return None, named, "no_country"
    if address.countries:
        named = [a for a in named if _country_named(a, address.countries)]
    tied = named + _not_ruled_out(named, distinct, address, path)
    if len(tied) == 1:
        if (not address.countries
                and _place_keys(_site_parts(tied[0]))
                != _place_keys(address.places)):
            return None, tied, "more_places"
        return tied[0], tied, "own_site"
    if tied:
        return None, tied, "own_site"
    if single is not None and not _is_place(single, path):
        if _country_named(single, address.countries):
            return single, [single], "own_country"
        implied, _ = _implied_country(address, path)
        if implied and _country_named(single, [implied]):
            return single, [single], "implied_country"
        if implied:
            return None, [], "other_implied_country"
        return None, [], "not_own_country"
    return None, [], "own_site"


def _by_rfq_text(single, rfq_countries):
    """(chosen account or None, accounts tied for it, rule) without the
    customer's own address: only the only exact-name account is accepted
    ("single"), and only when the RFQ text names its country. Otherwise
    nothing is chosen: the text names other countries ("other_country"),
    none of them ("country_not_named"), the account has no country
    ("no_account_country"), or several accounts share the name
    ("no_address")."""
    if single is None:
        return None, [], "no_address"
    if not single["country"]:
        return None, [], "no_account_country"
    if _country_named(single, rfq_countries):
        return single, [single], "single"
    if rfq_countries:
        return None, [], "other_country"
    return None, [], "country_not_named"


def _ordered(accounts, chosen, tied) -> list:
    """The chosen account first, then the tied ones, then the rest;
    identical rows once, at most 10."""
    first = [chosen] if chosen is not None else []
    return _distinct(first + list(tied) + list(accounts))[:10]


def _kams_by_name(accounts) -> dict:
    kams = {}
    for account in accounts:
        kams.setdefault(account["display_name"].lower(),
                        set()).add(account["kam_pte"])
    return kams


def _its_site(account) -> str:
    return f'its site "{account["site"]}"'


def _own_address(address) -> str:
    return f'the customer\'s own address in the RFQ ("{address.text}")'


def _implying(address, path=None) -> str:
    """Why the address lies in its implied country (_implied_country):
    '"ningbo" and "zhejiang" appear in Salesforce only under China'."""
    country, places = _implied_country(address, path)
    quoted = [f'"{place}"' for place in places]
    if len(quoted) == 1:
        return f"{quoted[0]} appears in Salesforce only under {country}"
    return (f"{', '.join(quoted[:-1])} and {quoted[-1]} appear in "
            f"Salesforce only under {country}")


def _chosen_reason(account, rule, address, path=None) -> str:
    if rule == "single":
        return ("Chosen: exact name match; the only account with this name "
                "in the Salesforce list, and the RFQ names its country "
                f'"{account["country"]}".')
    if rule == "own_country":
        return (f"Chosen: exact name match; the only account with this "
                f'name, and its country "{account["country"]}" is named in '
                f'the customer\'s own address ("{address.text}").')
    if rule == "implied_country":
        return (f"Chosen: exact name match; the only account with this "
                f'name, and the customer\'s own address ("{address.text}") '
                f'lies in its country "{account["country"]}" '
                f"({_implying(address, path)}).")
    return (f"Chosen: exact name match; {_its_site(account)} matches "
            f"{_own_address(address)}.")


def _tied_reason(account, rule, address, tied, path=None) -> str:
    """Why an account tied for the choice (_by_own_site) is not chosen: the
    address names its site, or cannot rule it out (_not_ruled_out)."""
    if rule == "no_country":
        return (f"Not chosen: {_its_site(account)} matches "
                f"{_own_address(address)}, but the address names no country "
                f"and accounts with this name are in more than one country.")
    if rule == "more_places":
        site = _place_keys(_site_parts(account))
        extra = ", ".join(f'"{p}"' for p in sorted(address.places)
                          if not _place_keys([p]) <= site)
        return (f"Not chosen: {_its_site(account)} matches "
                f"{_own_address(address)}, but the address names no country "
                f"and has other place parts ({extra}) that this site does "
                f"not account for, so it may be another place of the same "
                f"name.")
    if _names_site(account, address, path):
        return (f"Not chosen: {_its_site(account)} matches "
                f"{_own_address(address)}, but another candidate fits the "
                f"RFQ equally well.")
    if _inside_address(account, address):
        return (f"Not chosen: {_its_site(account)} appears inside a longer "
                f"place name in {_own_address(address)}, so the address "
                f"does not rule it out.")
    named = [n for n in tied if _names_site(n, address, path)]
    if any(_wider(account, n) for n in named):
        return (f"Not chosen: {_its_site(account)} is a more detailed site "
                f"of a place that {_own_address(address)} names, so the "
                f"address cannot tell it from that place's account.")
    if _fits_words(account, address):
        return (f"Not chosen: {_its_site(account)} also fits "
                f"{_own_address(address)}, so the accounts cannot be told "
                f"apart.")
    plain = next(n for n in named if _more_detailed(account, n))
    return (f'Not chosen: {_its_site(account)} contains "{plain["site"]}" '
            f"and may be a more detailed or a different location; the "
            f'customer\'s own address ("{address.text}") does not say which '
            f"one.")


def _not_a_place(account) -> str:
    return (f"{_its_site(account)} is not a specific place" if account["site"]
            else "it has no site")


def _not_chosen_reason(account, rule, address, rfq_countries, customer,
                       path=None) -> str:
    """Why an account that is neither chosen nor tied is out."""
    if rule == "avl":
        return "Not chosen: AVL is the supplier, not the customer."
    if rule == "partial_name":
        return (f'Not chosen: the company name only partly matches '
                f'"{customer}", so it may be a different legal entity.')
    if rule == "contained":
        return (f'Not chosen: all words of its name appear in "{customer}", '
                f"but the names differ, so it may be a different legal "
                f"entity.")
    if rule == "other_country":
        return (f'Not chosen: its country "{account["country"]}" is not '
                f"named in the RFQ, which names {', '.join(rfq_countries)} "
                f"instead.")
    if rule == "country_not_named":
        return ("Not chosen: the only account with this name, but the RFQ "
                "gives no customer address and does not name its country "
                f'"{account["country"]}".')
    if rule == "no_account_country":
        return ("Not chosen: the only account with this name, but the RFQ "
                "gives no customer address and the account has no country "
                "to check.")
    if rule == "not_own_country":
        return (f"Not chosen: {_not_a_place(account)}, and its country "
                f'"{account["country"]}" is not named in '
                f"{_own_address(address)}.")
    if rule == "other_implied_country":
        implied, _ = _implied_country(address, path)
        return (f"Not chosen: {_not_a_place(account)}, and "
                f"{_own_address(address)} lies in {implied} "
                f"({_implying(address, path)}), not in its country "
                f'"{account["country"]}".')
    if rule == "no_address":
        return ("Not chosen: several accounts share this name and the RFQ "
                "gives no customer address to tell them apart.")
    if not _is_place(account, path):
        return f"Not chosen: exact name match, but {_not_a_place(account)}."
    if _names_site(account, address, path):
        return (f"Not chosen: {_its_site(account)} is named in "
                f"{_own_address(address)}, but its country "
                f'"{account["country"]}" is not.')
    return (f"Not chosen: {_its_site(account)} does not match "
            f"{_own_address(address)}.")


def _details(customer, accounts, tier, chosen, tied, rule, address,
             rfq_countries, path=None) -> list:
    """Why each candidate was (not) chosen, in words for the slide notes.
    `rule` is the one _by_own_site() or _by_rfq_text() applied, "avl" when
    the customer is AVL itself, or "partial_name" / "contained" when no
    candidate has the exact name. Every tied row gets its own reason."""
    tied_keys = {_key(a) for a in tied}
    kams = _kams_by_name(accounts)
    out = []
    for a in _ordered(accounts, chosen, tied):
        if chosen is not None and _key(a) == _key(chosen):
            reason = _chosen_reason(a, rule, address, path)
        elif _key(a) in tied_keys:
            reason = _tied_reason(a, rule, address, tied, path)
        else:
            reason = _not_chosen_reason(a, rule, address, rfq_countries,
                                        customer, path)
        if (chosen is None and rule != "avl"
                and len(kams[a["display_name"].lower()]) > 1):
            reason = (reason[:-1] + "; the same account name is listed more "
                      "than once with different KAMs.")
        out.append({"account_name": a["display_name"], "site": a["site"],
                    "country": a["country"],
                    "kam_pte": a["kam_pte"] or INFO_NOT_AVAILABLE,
                    "match": tier, "reason": reason})
    return out


def clean_site(site) -> str:
    """The customer's own address as the account lookup reads it: the tags
    "(inferred)", "(not found)" and "(assumed)" dropped from either end (as
    often as they repeat), surrounding whitespace stripped, and "" for a
    value that means "no address" ("N/A", "Info not available", ...).
    Idempotent, so the stored lookup and the analysis it was made for can
    be compared through it (opportunity.account_match_is_current)."""
    text = str(site or "").strip()
    while True:
        stripped = _SITE_TAGS.sub("", text).strip()
        if stripped == text:
            break
        text = stripped
    return "" if fold(text) in _NO_SITE else text


def resolve_account(customer: str, corpus_text: str, site=None,
                    path=None) -> dict:
    """Pick the Salesforce account for `customer`, or say why not.

    `site` is the customer's OWN address as stage 1 read it from the RFQ
    (sender address, letterhead, signature block, contract party). It is
    the only evidence that chooses between accounts: place names elsewhere
    in the RFQ (delivery plants, suppliers, people called Troy, AVL's own
    address) say nothing about which account issued it. Junk values
    ("N/A", "unknown", "not found", "Info not available") count as no
    address; the tags "(inferred)", "(not found)" and "(assumed)" are
    dropped (clean_site; `customer_site` stores the cleaned value).

    `corpus_text` (the RFQ text) only counts without an own address, and
    only for the countries it names (AVL's own Austria left out).

    Deterministic and conservative - "Info not available" beats a wrong
    account:
      0. AVL is the supplier, never the customer: a customer named "AVL"
         or "AVL ..." gets no account;
      1. candidates = the best name tier (exact > all words > fuzzy >
         contained); only an exact name is ever chosen - the other tiers
         are listed as ambiguous;
      2. with an own address, read part by part (_read_address): the one
         account every part of whose site (a real place, not "Germany" or
         "HQ") equals a place part of the address - never one inside a
         longer name; spaces and the spellings of _SPELLINGS do not count -
         and whose country the address names; when it names none, only if
         every candidate is in one country and the site accounts for every
         place part of the address. Several, or another account the address
         cannot rule out (a more detailed site such as "Seosan-Jigok" next
         to "Seosan", a site inside a longer address part, a site whose
         words all appear in the address) -> ambiguous; none -> the only
         exact-name account if it has no specific place and the address
         names its country - or names none, but its places appear in the
         account list under that one country alone (_implied_country:
         "Ningbo, Zhejiang" lies in China) - else ambiguous;
      3. without one: the only exact-name account, and only when the RFQ
         text names its country; anything else is ambiguous.
    Every candidate gets a reason in `candidate_details`, the chosen
    account first; `candidate_count` counts the distinct rows.
    """
    tier, accounts = _candidates(customer, path)
    own_site = clean_site(site)
    distinct = _distinct(accounts)
    is_avl = normalize_name(customer).split()[:1] == ["avl"]
    result = {"customer": customer, "customer_site": own_site,
              "tier": tier,
              "account_name": INFO_NOT_AVAILABLE,
              "kam_pte": INFO_NOT_AVAILABLE,
              "candidates": [],
              "candidate_count": len(distinct)}
    if not accounts and not is_avl:
        return {**result, "status": "none", "candidate_details": []}

    single = distinct[0] if len(distinct) == 1 else None
    address, rfq_countries = None, []
    if is_avl:
        account, tied, rule = None, [], "avl"
    elif tier != "exact":
        account, tied = None, []
        rule = "contained" if tier == "contained" else "partial_name"
    elif own_site:
        address = _read_address(own_site, path)
        account, tied, rule = _by_own_site(accounts, distinct, single,
                                           address, path)
    else:
        if single is not None:
            rfq_countries = _rfq_countries(
                corpus_text, [customer] + [a["base"] for a in accounts],
                path)
        account, tied, rule = _by_rfq_text(single, rfq_countries)
    details = _details(customer, accounts, tier, account, tied, rule,
                       address, rfq_countries, path)
    result["candidates"] = [d["account_name"] for d in details]
    if account is None:
        return {**result, "status": "ambiguous", "candidate_details": details}
    return {**result,
            "status": "matched" if account["kam_pte"] else "no_kam",
            "account_name": account["display_name"],
            "kam_pte": account["kam_pte"] or INFO_NOT_AVAILABLE,
            "candidate_details": details}
